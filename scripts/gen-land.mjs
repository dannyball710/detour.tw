// Generates src/data/land.ts: a Pacific-centred equirectangular land outline as one SVG path.
// Units are degrees: x = longitude offset from CENTER_LON (−180..180), y = −latitude.
// Run: node scripts/gen-land.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { geoEquirectangular, geoPath } from 'd3-geo'
import { feature } from 'topojson-client'

const CENTER_LON = 150
const require = createRequire(import.meta.url)
const topo = JSON.parse(readFileSync(require.resolve('world-atlas/land-110m.json'), 'utf8'))
const land = feature(topo, topo.objects.land)

const projection = geoEquirectangular()
  .rotate([-CENTER_LON, 0])
  .scale(180 / Math.PI)
  .translate([0, 0])
  .precision(0.1)

const d = geoPath(projection).digits(1)(land)

writeFileSync(
  new URL('../src/data/land.ts', import.meta.url),
  `// Generated by scripts/gen-land.mjs from world-atlas land-110m (Natural Earth, public domain). Do not edit.
export const LAND_CENTER_LON = ${CENTER_LON}
export const LAND_PATH = ${JSON.stringify(d)}

/** Project lon/lat into the same coordinate space as LAND_PATH. */
export function project(lon: number, lat: number): [number, number] {
  const x = ((((lon - LAND_CENTER_LON) % 360) + 540) % 360) - 180
  return [x, -lat]
}
`,
)
console.log('land path chars:', d.length)
